test("recap styles, periods and palettes save independently for mobile", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1100 });

  const value = gallery();
  value.useSeparateMobileLayout = true;
  value.mobile = {
    columns: 4,
    widgets: value.desktop.widgets.map((widget, index) => ({
      ...widget,
      instanceId: `mobile-${widget.instanceId}`,
      x: 0,
      y: index * 4,
      width: 4,
    })),
  };
  const { state } = await mediaFixture(page, value);
  await page.getByRole("button", { name: "Customize", exact: true }).click();
  await selectWidget(page, page.locator('[data-widget-id$="poster"]'));
  await openWidgetTab(page, "Style");
  await page.clock.runFor(300);
  await customizeRecapPalette(page);

  await page.getByRole("button", { name: "Stories", exact: true }).click();
  await openWidgetTab(page, "Options");
  await page
    .getByRole("group", { name: "Recap month", exact: true })
    .getByRole("button", { name: "Last month", exact: true })
    .click();
  expect(state.writes).toHaveLength(0);
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByRole("button", { name: "Customize", exact: true })).toBeVisible();
  expect(state.saved.desktop.widgets[1]!.options.recapStyle).toBe(2);
  expect(state.saved.desktop.widgets[1]!.options.recapPeriod).toBe(1);
  expect(state.saved.mobile!.widgets[1]!.options.recapStyle).toBe(0);
  expect(state.saved.mobile!.widgets[1]!.options.recapPeriod).toBe(0);
  expect(state.saved.desktop.widgets[1]!.options.recapPalette).toEqual([
    "#123456",
    "#4cced4",
    "#ffe3b1",
  ]);
  expect(state.saved.mobile!.widgets[1]!.options.recapPalette ?? null).toBeNull();
  await expectRecapPaletteOnReload(page);
});

