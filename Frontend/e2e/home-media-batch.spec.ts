const gallery = (width = 6, height = 4) => {
  const value = seed();
  value.showWidgetTitles = true;
  const base = value.desktop.widgets[0]!;
  const perRow = Math.floor(12 / width);
  value.desktop.widgets = variants.map((variant, index) => ({
    ...base,
    instanceId: variant.id,
    type: variant.type,
    x: (index % perRow) * width,
    y: Math.floor(index / perRow) * height,
    width,
    height,
    options: { ...base.options, recapStyle: variant.recapStyle, recapPeriod: 0 },
  }));

  return value;
};

