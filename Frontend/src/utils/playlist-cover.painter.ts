export const renderCover = (
  spec: CoverSpec,
  dark: boolean,
  size: number,
): HTMLCanvasElement | null => {
  const key = coverKey(spec, dark, size);

  const hit = cache.get(key);
  if (hit) {
    cache.delete(key);
    cache.set(key, hit);
    return hit;
  }

  const canvas = document.createElement("canvas");
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext("2d");
  if (!ctx) return null;

  paintCover(ctx, spec, dark, size);

  cache.set(key, canvas);
  if (cache.size > CACHE_LIMIT) {
    const oldest = cache.keys().next().value;
    if (oldest !== undefined) cache.delete(oldest);
  }
  return canvas;
};

// Frame-budgeted paint queue: a burst of 30 covers is spread over several
// frames instead of landing in one long task.

const FRAME_BUDGET_MS = 6;

interface PaintJob {
  run: () => void;
  cancelled: boolean;
}
const queue: PaintJob[] = [];
let frameHandle = 0;

const flush = () => {
  frameHandle = 0;
  const start = performance.now();
  while (queue.length > 0) {
    const job = queue.shift();
    if (!job) break;
    if (!job.cancelled) job.run();
    if (performance.now() - start >= FRAME_BUDGET_MS) break;
  }
  if (queue.length > 0) frameHandle = requestAnimationFrame(flush);
};

export const enqueuePaint = (run: () => void): (() => void) => {
  const job: PaintJob = { run, cancelled: false };
  queue.push(job);
  if (!frameHandle) frameHandle = requestAnimationFrame(flush);
  return () => {
    job.cancelled = true;
  };
};

// One IntersectionObserver for every cover on the page. Reports both
// directions so offscreen covers can skip theme-change repaints.

let visibilityObserver: IntersectionObserver | null = null;
const visibilityCallbacks = new WeakMap<Element, (visible: boolean) => void>();

export const observeVisibility = (el: Element, onChange: (visible: boolean) => void) => {
  if (typeof IntersectionObserver === "undefined") {
    onChange(true);
    return () => undefined;
  }
  visibilityObserver ??= new IntersectionObserver(
    (entries) => {
      for (const entry of entries) {
        visibilityCallbacks.get(entry.target)?.(entry.isIntersecting);
      }
    },
    { rootMargin: "200px" },
  );
  visibilityCallbacks.set(el, onChange);
  visibilityObserver.observe(el);
  return () => {
    visibilityCallbacks.delete(el);
    visibilityObserver?.unobserve(el);
  };
};
