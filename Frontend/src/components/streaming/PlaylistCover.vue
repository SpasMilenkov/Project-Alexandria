<template>
  <div ref="boxRef" role="img" :aria-label="playlist.name" class="h-full w-full">
    <canvas v-if="!failed" ref="canvasRef" class="block h-full w-full" aria-hidden="true" />
    <div v-else class="flex h-full w-full items-center justify-center">
      <UIcon name="mdi:playlist-music" class="h-10 w-10 text-gray-300 dark:text-white/20" />
    </div>
  </div>
</template>

<script setup lang="ts">
import { onMounted, onUnmounted, ref, watch } from "vue";

import type { AutoGroupKind } from "@/enums/auto-group-kind";

import { useTheme } from "@/composables/useTheme";
import {
  bucketFor,
  coverKey,
  enqueuePaint,
  observeVisibility,
  renderCover,
} from "@/utils/playlist-cover.painter";

const { playlist } = defineProps<{
  playlist: {
    id: string;
    name: string;
    isAutoGenerated: boolean;
    autoGroupKind: AutoGroupKind | null;
  };
}>();

const boxRef = ref<HTMLDivElement | null>(null);
const canvasRef = ref<HTMLCanvasElement | null>(null);
const failed = ref(false);

const { isDark } = useTheme();

// Plain variables on purpose: none of these need to trigger a re-render.
let visible = false;
let boxSize = 0;
let paintedKey = "";
let cancelPaint: (() => void) | null = null;
let stopVisibility: (() => void) | null = null;
let resizeObserver: ResizeObserver | null = null;

const schedule = () => {
  cancelPaint?.();
  cancelPaint = null;
  if (!visible || boxSize < 8 || failed.value) return;

  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  const size = bucketFor(boxSize * dpr);
  const spec = { ...playlist };
  const dark = isDark.value;
  const key = coverKey(spec, dark, size);

  // Same content at the same bucket: a resize inside the bucket costs nothing.
  if (key === paintedKey) return;

  cancelPaint = enqueuePaint(() => {
    cancelPaint = null;
    const canvas = canvasRef.value;
    if (!canvas) return;

    const source = renderCover(spec, dark, size);
    const ctx = canvas.getContext("2d");
    if (!source || !ctx) {
      failed.value = true;
      return;
    }

    if (canvas.width !== size) {
      canvas.width = size;
      canvas.height = size;
    }
    ctx.drawImage(source, 0, 0);
    paintedKey = key;
  });
};

onMounted(() => {
  const box = boxRef.value;
  if (!box) return;

  stopVisibility = observeVisibility(box, (isVisible) => {
    visible = isVisible;
    schedule();
  });

  // contentRect avoids a getBoundingClientRect() layout read.
  resizeObserver = new ResizeObserver(([entry]) => {
    const { width, height } = entry.contentRect;
    boxSize = Math.floor(Math.min(width, height));
    schedule();
  });
  resizeObserver.observe(box);
});

onUnmounted(() => {
  cancelPaint?.();
  stopVisibility?.();
  resizeObserver?.disconnect();
});

watch(
  [
    () => playlist.id,
    () => playlist.name,
    () => playlist.isAutoGenerated,
    () => playlist.autoGroupKind,
    isDark,
  ],
  () => {
    failed.value = false;
    schedule();
  },
);
</script>
