import type { AutoGroupKind } from "../enums/auto-group-kind";
import type { PlaylistSort } from "../enums/playlist-sort";
import type { SortDirection } from "../enums/SortDirection";
import type { PaginatedResponse } from "./directory";
import type { StreamingRepresentationResponse } from "./streaming";

import { apiClient } from "./client";

// Response types

export interface PlaylistRepresentationResponse extends Pick<
  StreamingRepresentationResponse,
  "id" | "codec" | "width" | "height" | "status"
> {
  bitrateKbps?: number;
}

export interface PlaylistItemResponse {
  id: string;
  position: number;
  transpilationJobId: string;
  fileId: string;
  fileName: string;
  mimeType: string;
  segmentPrefix?: string;
  representations: PlaylistRepresentationResponse[];
  createdAt: string;
}

export interface PlaylistResponse {
  id: string;
  name: string;
  description?: string;
  hasCover: boolean;
  isStarred: boolean;
  ambientTheme?: string;
  itemCount: number;
  isAutoGenerated: boolean;
  autoGroupKind: AutoGroupKind | null;
  createdAt: string;
  updatedAt?: string;
}

export interface PlaylistFavoriteResponse {
  playlistId: string;
  isStarred: boolean;
}

export interface PlaylistDetailResponse {
  id: string;
  name: string;
  description?: string;
  hasCover: boolean;
  isStarred: boolean;
  ambientTheme?: string;
  isAutoGenerated: boolean;
  autoGroupKind: AutoGroupKind | null;
  items: PlaylistItemResponse[];
  createdAt: string;
  updatedAt?: string;
}

export interface GetPlaylistsFilters {
  isAutoGenerated?: boolean;
  autoGroupKind?: AutoGroupKind | null;
  isStarred?: boolean;
  sort?: PlaylistSort;
  sortDirection?: SortDirection;
  query?: string | null;
  searchItems?: boolean;
}

// Request types

export interface CreatePlaylistRequest {
  name: string;
  description?: string;
  /**
   * Pre-resolved cover URL. When omitted and initialTranspilationJobIds is non-empty,
   * the backend falls back to a random preview from those files.
   */
  hasCover: boolean;
  ambientTheme?: string;
  initialTranspilationJobIds?: string[];
}

export interface UpdatePlaylistRequest {
  name?: string;
  description?: string;
  hasCover?: boolean;
  ambientTheme?: string;
}

export interface AddPlaylistItemRequest {
  transpilationJobId: string;
}

export interface ReorderPlaylistItemsRequest {
  orderedItemIds: string[];
}

// API

export const playlistApi = {
  create: async (req: CreatePlaylistRequest): Promise<PlaylistResponse> => {
    const result = await apiClient.post<PlaylistResponse>("/playlists", req);
    return result.data;
  },

  getById: async (id: string): Promise<PlaylistDetailResponse> => {
    const result = await apiClient.get<PlaylistDetailResponse>(`/playlists/${id}`);
    return result.data;
  },

  getAll: async (
    page: number,
    pageSize: number,
    filters?: GetPlaylistsFilters,
  ): Promise<PaginatedResponse<PlaylistResponse>> => {
    const result = await apiClient.get<PaginatedResponse<PlaylistResponse>>("/playlists", {
      params: {
        page,
        pageSize,
        isAutoGenerated: filters?.isAutoGenerated,
        autoGroupKind: filters?.autoGroupKind ?? undefined,
        isStarred: filters?.isStarred ? true : undefined,
        sort: filters?.sort,
        direction: filters?.sortDirection,
        query: filters?.query ?? undefined,
        searchItems: filters?.searchItems ? true : undefined,
      },
    });
    return result.data;
  },

  uploadPlaylistCover: async (playlistId: string, file: File) => {
    const form = new FormData();
    form.append("playlistId", playlistId);
    form.append("file", file);

    // Drop the instance JSON content-type so the browser sets multipart
    // with its own boundary; the default transform would stringify the form.
    const result = await apiClient.post("/streaming/playlists/cover", form, {
      transformRequest: [
        (payload, headers) => {
          headers?.delete("Content-Type");
          return payload;
        },
      ],
    });

    return result.data;
  },

  // Stable, cookie-authed cover URL served by nginx (see the /covers/
  // location). The playlist updatedAt busts browser caches on re-upload
  // while the bytes stay long-lived cached server-side.
  getPlaylistCoverUrl: (playlistId: string, updatedAt?: string | null): string => {
    const base = `/covers/${playlistId}`;
    return updatedAt ? `${base}?v=${encodeURIComponent(updatedAt)}` : base;
  },

  update: async (id: string, req: UpdatePlaylistRequest): Promise<PlaylistResponse> => {
    const result = await apiClient.patch<PlaylistResponse>(`/playlists/${id}`, req);
    return result.data;
  },

  delete: async (id: string): Promise<void> => {
    await apiClient.delete(`/playlists/${id}`);
  },

  setFavorite: async (
    playlistId: string,
    isStarred: boolean,
  ): Promise<PlaylistFavoriteResponse> => {
    const result = await apiClient.patch<PlaylistFavoriteResponse>(
      `/playlists/${playlistId}/favorite`,
      { isStarred },
    );

    return result.data;
  },

  addItem: async (
    playlistId: string,
    req: AddPlaylistItemRequest,
  ): Promise<PlaylistItemResponse> => {
    const result = await apiClient.post<PlaylistItemResponse>(
      `/playlists/${playlistId}/items`,
      req,
    );
    return result.data;
  },

  removeItem: async (playlistId: string, itemId: string): Promise<void> => {
    await apiClient.delete(`/playlists/${playlistId}/items/${itemId}`);
  },

  reorderItems: async (playlistId: string, req: ReorderPlaylistItemsRequest): Promise<void> => {
    await apiClient.put(`/playlists/${playlistId}/items/order`, req);
  },
};
