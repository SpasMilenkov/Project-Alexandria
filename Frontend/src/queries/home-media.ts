import { defineQueryOptions } from "@pinia/colada";

import { playlistApi } from "@/api/playlist";
import { statsApi } from "@/api/stats";
import { streamingApi } from "@/api/streaming";
import { JobStatus } from "@/enums/job-status";
import { PLAYLIST_QUERY_KEYS } from "@/queries/playlist";
import { STREAMING_QUERY_KEYS } from "@/queries/streaming";
import { wrappedMonthRange } from "@/utils/wrapped-month";

interface HomeMediaSession {
  userId: string;
  epoch: number;
}

export const HOME_MEDIA_QUERY_KEYS = {
  jobsOwner: (userId: string) => [
    ...STREAMING_QUERY_KEYS.root,
    "transpilation-jobs",
    "home",
    userId,
  ],
  recapOwner: (userId: string) => ["stats", "wrapped", "home", userId],
  collectionsOwner: (userId: string) => [...PLAYLIST_QUERY_KEYS.root, "home", userId],
};

export const homeTranscodingJobs = defineQueryOptions((session: HomeMediaSession) => ({
  key: [...HOME_MEDIA_QUERY_KEYS.jobsOwner(session.userId), session.epoch],
  enabled: Boolean(session.userId),
  staleTime: 15_000,
  query: async () => ({
    ...session,
    value: await Promise.all(
      [JobStatus.Processing, JobStatus.Queued, JobStatus.Failed].map((status) =>
        streamingApi.getTranspilationJobs({ status, currentPage: 1, pageSize: 6 }),
      ),
    ),
  }),
}));

export const homeMonthlyRecap = defineQueryOptions(
  (params: HomeMediaSession & { month: string }) => ({
    key: [...HOME_MEDIA_QUERY_KEYS.recapOwner(params.userId), params.epoch, params.month],
    enabled: Boolean(params.userId),
    staleTime: 300_000,
    query: async () => {
      const range = wrappedMonthRange(params.month);

      return { ...params, value: await statsApi.getWrapped(range.from, range.to) };
    },
  }),
);

export const homeCollections = defineQueryOptions((session: HomeMediaSession) => ({
  key: [...HOME_MEDIA_QUERY_KEYS.collectionsOwner(session.userId), session.epoch],
  enabled: Boolean(session.userId),
  staleTime: 60_000,
  query: async () => ({
    ...session,
    value: await playlistApi.getAll(1, 4, { isAutoGenerated: true }),
  }),
}));
