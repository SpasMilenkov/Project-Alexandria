import { defineQueryOptions } from "@pinia/colada";

import { type TopSongsQuery, listeningRankingsApi } from "@/api/listening-rankings";
import { playlistApi } from "@/api/playlist";
import { streamingApi } from "@/api/streaming";
import { PlaylistSort } from "@/enums/playlist-sort";

interface MediaOverviewSession {
  userId: string;
  session: string;
}

export const mediaOverviewKey = ({ userId, session }: MediaOverviewSession) => [
  "media-overview",
  userId,
  session,
];

export const mediaOverviewLibrary = defineQueryOptions(
  (params: MediaOverviewSession & { isVideo: boolean }) => ({
    key: [...mediaOverviewKey(params), "library", params.isVideo],
    enabled: Boolean(params.userId),
    staleTime: 60_000,
    query: () =>
      streamingApi.getFilesForStreaming({
        page: 1,
        pageSize: params.isVideo ? 4 : 6,
        isVideo: params.isVideo,
      }),
  }),
);

export const mediaOverviewPlaylists = defineQueryOptions(
  (params: MediaOverviewSession & { automatic: boolean }) => ({
    key: [...mediaOverviewKey(params), "playlists", params.automatic],
    enabled: Boolean(params.userId),
    staleTime: 60_000,
    query: () =>
      playlistApi.getAll(1, params.automatic ? 6 : 4, {
        isAutoGenerated: params.automatic,
        sort: PlaylistSort.Newest,
      }),
  }),
);

export const mediaOverviewHistory = defineQueryOptions((params: MediaOverviewSession) => ({
  key: [...mediaOverviewKey(params), "history"],
  enabled: Boolean(params.userId),
  staleTime: 30_000,
  query: () => streamingApi.getHistory({ currentPage: 1, pageSize: 5 }),
}));

export const mediaOverviewOnRepeat = defineQueryOptions(
  (params: MediaOverviewSession & TopSongsQuery) => ({
    key: [...mediaOverviewKey(params), "on-repeat", params.from, params.to, params.limit],
    enabled: Boolean(params.userId),
    staleTime: 60_000,
    query: () =>
      listeningRankingsApi.getTopSongs({ from: params.from, to: params.to, limit: params.limit }),
  }),
);

export const mediaOverviewJumpBackIn = defineQueryOptions((params: MediaOverviewSession) => ({
  key: [...mediaOverviewKey(params), "jump-back-in"],
  enabled: Boolean(params.userId),
  staleTime: 60_000,
  query: () => listeningRankingsApi.getJumpBackIn({ limit: 6 }),
}));
