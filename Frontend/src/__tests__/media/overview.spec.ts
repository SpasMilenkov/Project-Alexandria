import { PiniaColada, useQueryCache } from "@pinia/colada";
import { flushPromises, mount } from "@vue/test-utils";
import { createPinia } from "pinia";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { defineComponent, h, reactive, ref } from "vue";

import type { MediaFileDto } from "@/api/streaming";

import MediaOverviewContent from "@/components/streaming/overview/MediaOverviewContent.vue";
import MediaOverviewFile from "@/components/streaming/overview/MediaOverviewFile.vue";
import { useSettingsStore } from "@/stores/settings";
import MediaOverviewView from "@/views/dashboard/streaming/MediaOverviewView.vue";

const api = vi.hoisted(() => ({
  files: vi.fn(),
  playlists: vi.fn(),
  history: vi.fn(),
  repeat: vi.fn(),
  jumpBackIn: vi.fn(),
  timeline: vi.fn(),
  streamingFile: vi.fn(),
}));

vi.mock("@/api/listening-rankings", () => ({
  listeningRankingsApi: { getTopSongs: api.repeat, getJumpBackIn: api.jumpBackIn },
}));

vi.mock("@/api/streaming", () => ({
  streamingApi: {
    getFilesForStreaming: api.files,
    getHistory: api.history,
    getStreamingFile: api.streamingFile,
  },
}));
vi.mock("@/api/stats", () => ({ statsApi: { getTimeline: api.timeline } }));
vi.mock("@/api/playlist", () => ({ playlistApi: { getAll: api.playlists } }));

const player = reactive({
  activeFile: null as MediaFileDto | null,
  isPlaying: false,
  playbackOwnerId: "alice",
  orderBusy: false,
  playTrackInContext: vi.fn(),
  playNow: vi.fn(),
  togglePlay: vi.fn(),
  startContext: vi.fn(),
});

vi.mock("@/stores/stream-player", () => ({ usePlayerStore: () => player }));

const Button = defineComponent({
  setup:
    (_, { slots }) =>
    () =>
      h("button", slots.default?.()),
});

const Link = defineComponent({
  setup:
    (_, { slots }) =>
    () =>
      h("a", slots.default?.()),
});

const media = (title = "New song"): MediaFileDto => ({
  fileId: title,
  fileName: "song.mp3",
  title,
  artist: "Artist",
  album: null,
  genre: null,
  year: null,
  duration: 240,
  mimeType: "audio/mpeg",
  currentVersionId: "current",
  playbackVersionId: "playable",
  transpilationJobId: "job",
  isVideo: false,
  segmentPrefix: null,
});

const cleanups: (() => void)[] = [];

const mountOverview = () => {
  const owner = ref("alice");
  const pinia = createPinia();
  const wrapper = mount(
    defineComponent({
      setup: () => () => h(MediaOverviewContent, { userId: owner.value, key: owner.value }),
    }),
    {
      global: {
        plugins: [pinia, PiniaColada],
        stubs: {
          Button,
          UButton: Button,
          UIcon: true,
          RouterLink: Link,
          HomeCollectionCover: true,
          UPopover: true,
        },
      },
    },
  );
  cleanups.push(() => wrapper.unmount());

  return { wrapper, owner, cache: useQueryCache(pinia) };
};

beforeEach(() => {
  vi.clearAllMocks();
  api.files.mockResolvedValue({ items: [media()], totalCount: 37 });
  api.playlists.mockResolvedValue({ items: [], totalCount: 0 });
  api.history.mockResolvedValue({ items: [], totalCount: 0 });
  api.repeat.mockResolvedValue({
    items: [{ file: media("Favorite"), qualifiedPlayCount: 12, totalListenedSeconds: 3000 }],
  });
  api.timeline.mockResolvedValue({
    days: [],
    totalSeconds: 0,
    qualifiedPlayCount: 0,
    activeDays: 0,
  });
  api.streamingFile.mockResolvedValue(null);
  api.jumpBackIn.mockResolvedValue({
    inactiveDays: 30,
    inactiveBefore: "2026-09-09T12:00:00Z",
    items: [
      {
        file: media("Old favorite"),
        qualifiedPlayCount: 20,
        totalListenedSeconds: 4800,
        lastPlayedAt: "2026-08-01T12:00:00Z",
      },
    ],
  });
  player.activeFile = null;
  player.playbackOwnerId = "alice";
  player.orderBusy = false;
  player.isPlaying = false;
});

afterEach(() => {
  cleanups.splice(0).forEach((cleanup) => cleanup());
  vi.restoreAllMocks();
  vi.unstubAllEnvs();
});

describe("Media overview", () => {
  it("loads bounded server lists and rankings using returned totals and play counts", async () => {
    const { wrapper } = mountOverview();
    await flushPromises();

    expect(api.files.mock.calls).toEqual([
      [{ page: 1, pageSize: 12, isVideo: false }],
      [{ page: 1, pageSize: 8, isVideo: true }],
    ]);
    expect(api.playlists).toHaveBeenCalledTimes(2);
    expect(api.playlists).toHaveBeenCalledWith(1, 4, { isAutoGenerated: false, sort: 0 });
    expect(api.playlists).toHaveBeenCalledWith(1, 10, { isAutoGenerated: true, sort: 0 });
    expect(api.history).toHaveBeenCalledExactlyOnceWith({ currentPage: 1, pageSize: 6 });
    expect(api.repeat).toHaveBeenCalledOnce();
    expect(api.repeat.mock.calls[0]![0].limit).toBe(6);
    expect(api.jumpBackIn).toHaveBeenCalledExactlyOnceWith({ limit: 10 });
    expect(api.timeline).toHaveBeenCalledOnce();
    expect(api.timeline.mock.calls[0]).toEqual([
      api.repeat.mock.calls[0]![0].from,
      api.repeat.mock.calls[0]![0].to,
    ]);
    expect(wrapper.text()).toContain("37 tracks");
    expect(wrapper.text()).toContain("Favorite");
    expect(wrapper.text()).toContain("50m");
    expect(wrapper.text()).toContain("Old favorite");
    expect(player.playTrackInContext).not.toHaveBeenCalled();
    expect(player.togglePlay).not.toHaveBeenCalled();
    expect(player.playNow).not.toHaveBeenCalled();
  });

  it("keeps other sections usable when one source fails and retries only that source", async () => {
    api.files.mockImplementation(({ isVideo }) => {
      if (isVideo) return Promise.reject(new Error("Unavailable"));

      return Promise.resolve({ items: [media()], totalCount: 1 });
    });
    const { wrapper } = mountOverview();
    await flushPromises();

    expect(wrapper.text()).toContain("New song");
    expect(wrapper.get('[role="alert"]').text()).toContain("Couldn’t load videos");
    expect(wrapper.text()).toContain("No playlists yet");
    api.files.mockResolvedValue({ items: [], totalCount: 0 });
    await wrapper.get('[role="alert"] button').trigger("click");
    await flushPromises();

    expect(wrapper.text()).toContain("No videos ready yet");
    expect(api.files).toHaveBeenCalledTimes(3);
    expect(api.playlists).toHaveBeenCalledTimes(2);
    expect(api.history).toHaveBeenCalledTimes(1);
  });

  it("discards old account queries and ignores their late responses", async () => {
    let resolveOld = (_value: { items: MediaFileDto[]; totalCount: number }) => {};
    const pending = new Promise<{ items: MediaFileDto[]; totalCount: number }>((resolve) => {
      resolveOld = resolve;
    });
    api.files.mockReturnValue(pending);
    const { wrapper, owner, cache } = mountOverview();
    await flushPromises();
    api.files.mockResolvedValue({ items: [media("Bob’s song")], totalCount: 1 });
    owner.value = "bob";
    await flushPromises();
    resolveOld({ items: [media("Alice’s private song")], totalCount: 1 });
    await flushPromises();

    expect(wrapper.text()).toContain("Bob’s song");
    expect(wrapper.text()).not.toContain("Alice’s private song");
    expect(cache.getEntries({ key: ["media-overview", "alice"] })).toHaveLength(0);
  });

  it("starts a fresh page session when the same owner returns", async () => {
    const first = mountOverview();
    await flushPromises();
    first.wrapper.unmount();
    cleanups.pop();
    api.files.mockResolvedValue({ items: [media("Fresh session")], totalCount: 1 });
    const second = mountOverview();
    await flushPromises();

    expect(second.wrapper.text()).toContain("Fresh session");
    expect(api.files).toHaveBeenCalledTimes(4);
  });

  it("uses playback-version artwork and the existing library player command", async () => {
    const pinia = createPinia();
    const settings = useSettingsStore(pinia);
    settings.thumbnailsEnabled = true;
    const file = media();
    const wrapper = mount(MediaOverviewFile, {
      props: { file, userId: "alice" },
      global: { plugins: [pinia], stubs: { UIcon: true } },
    });
    cleanups.push(() => wrapper.unmount());

    expect(wrapper.get("img").attributes("src")).toContain("playable");
    await wrapper.get("button").trigger("click");
    expect(player.playTrackInContext).toHaveBeenCalledExactlyOnceWith(
      file,
      { isVideo: false, playlistId: null },
      "Music",
    );
    player.activeFile = file;
    player.isPlaying = true;
    await flushPromises();
    await wrapper.get("button").trigger("click");
    expect(player.togglePlay).toHaveBeenCalledOnce();

    settings.thumbnailsEnabled = false;
    await flushPromises();
    expect(wrapper.find("img").exists()).toBe(false);
    player.playbackOwnerId = "bob";
    await flushPromises();
    expect(wrapper.get("button").attributes("disabled")).toBeDefined();
  });

  it("plays an On repeat result directly without rebuilding or joining the library", async () => {
    const { wrapper } = mountOverview();
    await flushPromises();
    await wrapper.get('button[aria-label="Play Favorite"]').trigger("click");

    expect(player.playNow).toHaveBeenCalledExactlyOnceWith([media("Favorite")]);
    expect(player.playTrackInContext).not.toHaveBeenCalled();
    expect(api.files).toHaveBeenCalledTimes(2);
  });

  it("makes no media requests when streaming is disabled", async () => {
    vi.stubEnv("VITE_STREAMING_ENABLED", "false");
    const wrapper = mount(MediaOverviewView, {
      global: {
        plugins: [createPinia(), PiniaColada],
        stubs: { Button, UButton: Button, UIcon: true },
      },
    });
    cleanups.push(() => wrapper.unmount());
    await flushPromises();

    expect(wrapper.text()).toContain("Media streaming is unavailable");
    expect(api.files).not.toHaveBeenCalled();
    expect(api.history).not.toHaveBeenCalled();
    expect(api.playlists).not.toHaveBeenCalled();
    expect(api.repeat).not.toHaveBeenCalled();
    expect(api.jumpBackIn).not.toHaveBeenCalled();
  });

  it("plays a Jump back in result directly and retries only its failed source", async () => {
    api.jumpBackIn.mockRejectedValueOnce(new Error("Unavailable"));
    const { wrapper } = mountOverview();
    await flushPromises();

    expect(wrapper.text()).toContain("Favorite");
    expect(wrapper.get('[role="alert"]').text()).toContain("Couldn’t load jump back in");
    await wrapper.get('[role="alert"] button').trigger("click");
    await flushPromises();
    await wrapper.get('button[aria-label="Play Old favorite"]').trigger("click");

    expect(api.jumpBackIn).toHaveBeenCalledTimes(2);
    expect(api.files).toHaveBeenCalledTimes(2);
    expect(api.repeat).toHaveBeenCalledTimes(1);
    expect(player.playNow).toHaveBeenCalledExactlyOnceWith([media("Old favorite")]);
    expect(player.playTrackInContext).not.toHaveBeenCalled();
  });
});

describe("Media overview sections", () => {
  it("welcomes an empty library with the policy guidance instead of empty shelves", async () => {
    api.files.mockResolvedValue({ items: [], totalCount: 0 });
    const { wrapper } = mountOverview();
    await flushPromises();

    expect(wrapper.text()).toContain("Your library starts here");
    expect(wrapper.text()).toContain("Drop audio or video files in a directory with a");
    expect(wrapper.text()).toContain("What you will find here");
    expect(wrapper.text()).not.toContain("Fresh in your library ·");
  });

  it("groups recent plays by day with artist and video resume details", async () => {
    const now = new Date().toISOString();
    api.history.mockResolvedValue({
      items: [
        {
          id: "h1",
          fileId: "song",
          title: "Played song",
          artist: "Played artist",
          album: null,
          duration: 200,
          isVideo: false,
          positionSeconds: 30,
          hasFinished: false,
          lastAccessedAt: now,
        },
        {
          id: "h2",
          fileId: "film",
          title: "Watched film",
          artist: null,
          album: null,
          duration: 600,
          isVideo: true,
          positionSeconds: 120,
          hasFinished: false,
          lastAccessedAt: now,
        },
      ],
      totalCount: 2,
    });
    const { wrapper } = mountOverview();
    await flushPromises();

    expect(wrapper.text()).toContain("Today");
    expect(wrapper.text()).toContain("Played artist");
    expect(wrapper.text()).toContain("Video · stopped at 2:00");
    expect(wrapper.text()).toContain("Pick up where you left off");
  });

  it("resumes the last played file through the streaming file lookup", async () => {
    api.history.mockResolvedValue({
      items: [
        {
          id: "h1",
          fileId: "Resumed",
          title: "Resumed",
          artist: "Artist",
          album: null,
          duration: 240,
          isVideo: false,
          positionSeconds: 60,
          hasFinished: false,
          lastAccessedAt: new Date().toISOString(),
        },
      ],
      totalCount: 1,
    });
    api.streamingFile.mockResolvedValue(media("Resumed"));
    const { wrapper } = mountOverview();
    await flushPromises();

    const resume = wrapper.findAll("button").find((button) => button.text().startsWith("Resume"));
    await resume!.trigger("click");
    await flushPromises();

    expect(api.streamingFile).toHaveBeenCalledExactlyOnceWith("Resumed");
    expect(player.playNow).toHaveBeenCalledExactlyOnceWith([media("Resumed")]);
  });

  it("summarizes this week's listening from the timeline", async () => {
    api.timeline.mockResolvedValue({
      days: [{ date: "2026-10-30", seconds: 3900, plays: 3, sessionCount: 4, top: [] }],
      totalSeconds: 3900,
      qualifiedPlayCount: 3,
      activeDays: 1,
    });
    const { wrapper } = mountOverview();
    await flushPromises();

    expect(wrapper.text()).toContain("1h 5m");
    expect(wrapper.text()).toContain("3 songs played · active 1 of 7 days");
  });
});
