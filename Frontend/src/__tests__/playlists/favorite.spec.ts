import { PiniaColada, useQuery } from "@pinia/colada";
import { createPinia, setActivePinia } from "pinia";
import { beforeEach, describe, expect, it, vi } from "vitest";
import { createApp, defineComponent, watchEffect } from "vue";

import type { PlaylistResponse } from "@/api/playlist";

import { PlaylistSort } from "@/enums/playlist-sort";
import { SortDirection } from "@/enums/SortDirection";

const { mockGetAll, mockSetFavorite } = vi.hoisted(() => ({
  mockGetAll: vi.fn(),
  mockSetFavorite: vi.fn(),
}));

vi.mock("@/api/playlist", () => ({
  playlistApi: {
    getAll: mockGetAll,
    setFavorite: mockSetFavorite,
  },
}));

vi.mock("@/stores/stream-player", () => ({
  usePlayerStore: () => ({ contextSourceChanged: vi.fn() }),
}));

const playlist = (isStarred: boolean): PlaylistResponse => ({
  id: "playlist-1",
  name: "Mixtape",
  hasCover: false,
  isStarred,
  itemCount: 3,
  isAutoGenerated: false,
  autoGroupKind: null,
  createdAt: "2026-10-01T00:00:00Z",
});

const pageWith = (isStarred: boolean) => ({
  items: [playlist(isStarred)],
  currentPage: 1,
  pageSize: 20,
  totalCount: 1,
  totalPages: 1,
});

// Mirrors PlaylistView: a getter key returning a fresh array per evaluation,
// the same placeholderData, and the app's global 30 s staleTime.
const mountViewProbe = async () => {
  const { setPlaylistFavorite } = await import("@/mutations/playlists");
  const { PLAYLIST_QUERY_KEYS } = await import("@/queries/playlist");

  const captured = {} as {
    mutation: ReturnType<typeof setPlaylistFavorite>;
    visible: { items: PlaylistResponse[] };
  };
  captured.visible = { items: [] };

  const pinia = createPinia();
  const app = createApp(
    defineComponent({
      setup() {
        const query = useQuery({
          key: () =>
            PLAYLIST_QUERY_KEYS.list(
              1,
              20,
              undefined,
              undefined,
              undefined,
              PlaylistSort.Newest,
              SortDirection.Desc,
              null,
              false,
            ),
          placeholderData: (prev) => prev,
          query: () => mockGetAll(1, 20),
        });

        captured.mutation = setPlaylistFavorite();

        watchEffect(() => {
          captured.visible.items = query.data.value?.items ?? [];
        });

        return () => null;
      },
    }),
  );

  app.use(pinia);
  app.use(PiniaColada, { queryOptions: { staleTime: 30_000 } });
  app.mount(document.createElement("div"));

  return { app, mutation: captured.mutation, visible: captured.visible };
};

describe("playlist favorite mutations", () => {
  beforeEach(() => {
    setActivePinia(createPinia());
    mockGetAll.mockReset();
    mockSetFavorite.mockReset();
  });

  it("the list query refetches after a favorite toggle and exposes the new state", async () => {
    mockGetAll.mockResolvedValueOnce(pageWith(false)).mockResolvedValueOnce(pageWith(true));
    mockSetFavorite.mockResolvedValue({ playlistId: "playlist-1", isStarred: true });

    const { app, mutation, visible } = await mountViewProbe();

    await vi.waitFor(() => expect(visible.items[0]?.isStarred).toBe(false));
    expect(mockGetAll).toHaveBeenCalledTimes(1);

    await mutation.mutateAsync({ playlistId: "playlist-1", isStarred: true });

    await vi.waitFor(() => expect(mockGetAll).toHaveBeenCalledTimes(2));
    await vi.waitFor(() => expect(visible.items[0]?.isStarred).toBe(true));

    app.unmount();
  });
});
