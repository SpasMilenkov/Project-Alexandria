    }

    public async Task<PaginatedResult<PlaylistDto>> GetByUserAsync(
        Guid userId,
        int page,
        int pageSize,
        bool? isAutoGenerated = null,
        AutoGroupKind? kind = null,
        bool isStarred = false,
        PlaylistSort sort = PlaylistSort.Newest,
        SortDirection direction = SortDirection.Desc,
        string? query = null,
        bool searchItems = false,
        CancellationToken ct = default)
    {
        var playlistsQuery = _playlists
            .Where(p => p.OwnerId == userId && p.DeletedAt == null);

        if (isAutoGenerated.HasValue)
            playlistsQuery = playlistsQuery.Where(p => p.IsAutoGenerated == isAutoGenerated.Value);

        if (kind.HasValue)
            playlistsQuery = playlistsQuery.Where(p => p.IsAutoGenerated && p.AutoGroupKind == kind.Value);

        if (isStarred)
            playlistsQuery = playlistsQuery.Where(p => p.IsStarred);

        var searchTerm = query?.Trim();
        if (!string.IsNullOrWhiteSpace(searchTerm))
            playlistsQuery = ApplySearchFilter(playlistsQuery, searchTerm, searchItems);

        var count = await playlistsQuery.CountAsync(ct);

        playlistsQuery = ApplySort(playlistsQuery, sort, direction);

        var items = await playlistsQuery
            .Skip((page - 1) * pageSize)
            .Take(pageSize)
            .Select(p => new PlaylistDto
            {
                Id = p.Id,
                Name = p.Name,
                Description = p.Description,
                HasCover = p.HasCover,
                IsStarred = p.IsStarred,
                AmbientTheme = p.AmbientTheme,
                ItemCount = p.PlaylistItems!.Count(i => i.DeletedAt == null),
                IsAutoGenerated = p.IsAutoGenerated,
                AutoGroupKind = p.AutoGroupKind,
                CreatedAt = p.CreatedAt,
                UpdatedAt = p.UpdatedAt
            })
            .ToListAsync(ct);

        return new PaginatedResult<PlaylistDto>
        {
            Items = items,
            CurrentPage = page,
            PageSize = pageSize,
            TotalCount = count,
            TotalPages = (int)Math.Ceiling(count / (double)pageSize)
        };
    }

    // ILIKE against a null description/title is false, so no guards are needed.
    // The item subquery only joins when the wider scope is requested; otherwise
    // it stays out of the SQL entirely.
    internal static IQueryable<Playlist> ApplySearchFilter(
        IQueryable<Playlist> playlists, string searchTerm, bool searchItems)
    {
        var pattern = $"%{searchTerm}%";

        return searchItems
            ? playlists.Where(p =>
                EF.Functions.ILike(p.Name, pattern)
                || EF.Functions.ILike(p.Description!, pattern)
                || p.PlaylistItems!.Any(i =>
                    i.DeletedAt == null
                    && (EF.Functions.ILike(i.TranspilationJob!.FileVersion.File.Name, pattern)
                        || EF.Functions.ILike(
                            i.TranspilationJob!.FileVersion.File.MediaMetadata!.Title!, pattern))))
            : playlists.Where(p =>
                EF.Functions.ILike(p.Name, pattern)
                || EF.Functions.ILike(p.Description!, pattern));
    }

    // The direction only flips the primary key; tie-breakers keep their fixed
    // ordering so equal rows stay stable in both directions.
    internal static IQueryable<Playlist> ApplySort(
        IQueryable<Playlist> playlists, PlaylistSort sort, SortDirection direction)
    {
        var descending = direction == SortDirection.Desc;

        return sort switch
        {
            PlaylistSort.Name => descending
                ? playlists.OrderByDescending(p => p.Name)
                    .ThenByDescending(p => p.CreatedAt)
                    .ThenByDescending(p => p.Id)
                : playlists.OrderBy(p => p.Name)
                    .ThenByDescending(p => p.CreatedAt)
                    .ThenBy(p => p.Id),

            PlaylistSort.TrackCount => descending
                ? playlists
                    .OrderByDescending(p => p.PlaylistItems!.Count(i => i.DeletedAt == null))
                    .ThenBy(p => p.Name)
                    .ThenBy(p => p.Id)
                : playlists
                    .OrderBy(p => p.PlaylistItems!.Count(i => i.DeletedAt == null))
                    .ThenBy(p => p.Name)
                    .ThenBy(p => p.Id),

            _ => descending
                ? playlists.OrderByDescending(p => p.CreatedAt).ThenByDescending(p => p.Id)
                : playlists.OrderBy(p => p.CreatedAt).ThenBy(p => p.Id),
        };
    }

    public async Task SoftDeleteAsync(Guid playlistId, Guid userId, CancellationToken ct = default)
    {
        var now = DateTime.UtcNow;

        await _playlistItems
            .Where(i => i.PlaylistId == playlistId && i.DeletedAt == null)
            .ExecuteUpdateAsync(s => s
                .SetProperty(i => i.DeletedAt, now)
                .SetProperty(i => i.UpdatedAt, now)
                .SetProperty(i => i.UpdatedBy, userId), ct);

        await _playlists
            .Where(p => p.Id == playlistId && p.OwnerId == userId && p.DeletedAt == null)
            .ExecuteUpdateAsync(s => s
                .SetProperty(p => p.DeletedAt, now)
                .SetProperty(p => p.UpdatedAt, now)
                .SetProperty(p => p.UpdatedBy, userId), ct);
    }

    public async Task ReorderItemsAsync(
        Guid playlistId, Guid[] orderedItemIds, CancellationToken ct = default)
    {
        var items = await _playlistItems
            .Where(i => i.PlaylistId == playlistId && i.DeletedAt == null)
            .ToListAsync(ct);

        var positionMap = orderedItemIds
            .Select((id, index) => (id, index))
            .ToDictionary(x => x.id, x => x.index);

        var now = DateTime.UtcNow;
        foreach (var item in items)
        {
            if (!positionMap.TryGetValue(item.Id, out var position))
                continue;

            item.Position = position;
            item.UpdatedAt = now;
        }

        await context.SaveChangesAsync(ct);
    }

    public async Task<PlaylistItemDto> AddItemAsync(PlaylistItem item, CancellationToken ct = default)
    {
        // A live row means the track is already in the playlist, so the add is a
        // no-op instead of a duplicate. Otherwise a user-removed tombstone is
        // resurrected, and only a track with no row at all is inserted.
        var liveItemId = await _playlistItems
            .Where(i => i.PlaylistId == item.PlaylistId
                        && i.TranspilationJobId == item.TranspilationJobId
                        && i.DeletedAt == null)
            .Select(i => (Guid?)i.Id)
            .FirstOrDefaultAsync(ct);

        if (liveItemId is not null)
            return await GetItemDtoAsync(liveItemId.Value, ct);

        var tombstone = await _playlistItems
            .Where(i => i.PlaylistId == item.PlaylistId
                        && i.TranspilationJobId == item.TranspilationJobId
                        && i.DeletedAt != null)
            .OrderByDescending(i => i.DeletedAt)
            .FirstOrDefaultAsync(ct);

        if (tombstone is not null)
        {
            var maxPosition = await _playlistItems
                .Where(i => i.PlaylistId == item.PlaylistId && i.DeletedAt == null)
                .MaxAsync(i => (int?)i.Position, ct) ?? -1;

            tombstone.DeletedAt = null;
            tombstone.UpdatedAt = DateTime.UtcNow;
            tombstone.UpdatedBy = item.UpdatedBy;
            tombstone.RemovedByUser = false;
            tombstone.AddedByUser = item.AddedByUser;
            tombstone.Position = maxPosition + 1;
            await context.SaveChangesAsync(ct);

            return await GetItemDtoAsync(tombstone.Id, ct);
        }

        var max = await _playlistItems
            .Where(i => i.PlaylistId == item.PlaylistId && i.DeletedAt == null)
            .MaxAsync(i => (int?)i.Position, ct) ?? -1;

        item.Position = max + 1;
        item.CreatedAt = DateTime.UtcNow;

        await _playlistItems.AddAsync(item, ct);
        await context.SaveChangesAsync(ct);

        return await GetItemDtoAsync(item.Id, ct);
    }

    private Task<PlaylistItemDto> GetItemDtoAsync(Guid itemId, CancellationToken ct)
    {
        return _playlistItems
            .Where(i => i.Id == itemId)
            .Select(i => new PlaylistItemDto
            {
                Id = i.Id,
                Position = i.Position,
                TranspilationJobId = i.TranspilationJobId,
                FileId = i.TranspilationJob!.FileVersion.FileId,
                FileName = i.TranspilationJob!.FileVersion.File.Name,
                MimeType = i.TranspilationJob!.FileVersion.File.MimeType,
                SegmentPrefix = i.TranspilationJob!.SegmentPrefix,
                CreatedAt = i.CreatedAt,
                Representations = i.TranspilationJob!.Representations
                    .Where(r => r.DeletedAt == null)
                    .Select(r => new StreamingRepresentationDto
                    {
                        Id = r.Id,
                        Codec = r.Codec,
                        Width = r.Width,
                        Height = r.Height,
                        BitrateKbps = r.BitrateKbps,
                        Status = r.Status
                    })
                    .ToList()
            })
            .FirstAsync(ct);
    }

    public async Task RemoveItemAsync(
        Guid playlistId, Guid itemId, Guid userId, CancellationToken ct = default)
    {
        var now = DateTime.UtcNow;

        // User removal through the normal API. The flag is what keeps the
        // reconciler from silently re-adding the track on the next sync.
        await _playlistItems
            .Where(i => i.Id == itemId && i.PlaylistId == playlistId && i.DeletedAt == null)
            .ExecuteUpdateAsync(s => s
                .SetProperty(i => i.DeletedAt, now)
                .SetProperty(i => i.UpdatedAt, now)
                .SetProperty(i => i.UpdatedBy, userId)
                .SetProperty(i => i.RemovedByUser, true), ct);
    }

