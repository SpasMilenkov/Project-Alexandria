                            && t.DeletedAt == null
                            && t.Facet == TagFacet.Genre))
            .Select(p => p.Id)
            .ToListAsync(ct);
    }

    public async Task<IReadOnlyList<Guid>> GetOwnersNeedingSyncAsync(
        bool forceFull, CancellationToken ct = default)
    {
        // Owners with a live automatic playlist need reaping even after their last
        // file disappears. Owners with a resolvable transcode can still materialize
        // their first playlists; the job predicates mirror PlaylistJobResolver.
        var playlistOwners = _playlists
            .Where(p => p.DeletedAt == null && p.IsAutoGenerated)
            .Select(p => p.OwnerId);

        var jobOwners = context.TranspilationJobs
            .Where(tj => tj.DeletedAt == null
                         && tj.Job.DeletedAt == null
                         && tj.Job.Status == JobStatus.Ready
                         && tj.FileVersion.DeletedAt == null
                         && tj.FileVersion.File.DeletedAt == null
                         && tj.FileVersion.File.OwnerId == tj.UserId
                         && tj.Representations.Any(r =>
                             r.DeletedAt == null && r.Status == RepresentationStatus.Ready))
            .Select(tj => tj.UserId);

        var ownerIds = await playlistOwners
            .Union(jobOwners)
            .ToListAsync(ct);

        if (ownerIds.Count == 0)
            return [];

        if (forceFull)
            return ownerIds;

        var markers = (await _playlists
                .Where(p => ownerIds.Contains(p.OwnerId)
                            && p.DeletedAt == null
                            && p.IsAutoGenerated)
                .Select(p => new { p.OwnerId, p.LastSyncedAt })
                .ToListAsync(ct))
            .GroupBy(p => p.OwnerId)
            .ToDictionary(
                g => g.Key,
                g => new
                {
                    Oldest = g.Min(p => p.LastSyncedAt),
                    HasUnsynced = g.Any(p => p.LastSyncedAt is null),
                });

        var latestChange = new Dictionary<Guid, DateTime>();

        void Track(Guid ownerId, DateTime? changedAt)
        {
            if (changedAt is null)
                return;

            if (!latestChange.TryGetValue(ownerId, out var current) || changedAt > current)
                latestChange[ownerId] = changedAt.Value;
        }

        // File rows cover uploads, renames and soft deletions.
        foreach (var row in await context.Files
                     .Where(f => ownerIds.Contains(f.OwnerId))
                     .Select(f => new
                     {
                         f.OwnerId,
                         f.CreatedAt,
                         f.UpdatedAt,
                         f.DeletedAt,
                     })
                     .GroupBy(f => f.OwnerId)
                     .Select(g => new
                     {
                         OwnerId = g.Key,
                         Created = g.Max(f => f.CreatedAt),
                         Updated = g.Max(f => f.UpdatedAt),
                         Deleted = g.Max(f => f.DeletedAt),
                     })
                     .ToListAsync(ct))
        {
            Track(row.OwnerId, row.Created);
            Track(row.OwnerId, row.Updated);
            Track(row.OwnerId, row.Deleted);
        }

        // Metadata edits change artist/album/genre/year groupings.
        foreach (var row in await context.MediaMetadata
                     .Where(m => ownerIds.Contains(m.File!.OwnerId))
                     .Select(m => new
                     {
                         OwnerId = m.File!.OwnerId,
                         m.CreatedAt,
                         m.UpdatedAt,
                         m.DeletedAt,
                     })
                     .GroupBy(m => m.OwnerId)
                     .Select(g => new
                     {
                         OwnerId = g.Key,
                         Created = g.Max(m => m.CreatedAt),
                         Updated = g.Max(m => m.UpdatedAt),
                         Deleted = g.Max(m => m.DeletedAt),
                     })
                     .ToListAsync(ct))
        {
            Track(row.OwnerId, row.Created);
            Track(row.OwnerId, row.Updated);
            Track(row.OwnerId, row.Deleted);
        }

        // Tag links and tag vocabulary drive tag/genre rollups. Tag rows are
        // joined through the file so an unrelated owner is not marked dirty.
        foreach (var row in await context.FileTags
                     .Where(ft => ownerIds.Contains(ft.File.OwnerId))
                     .Select(ft => new
                     {
                         OwnerId = ft.File.OwnerId,
                         LinkCreatedAt = ft.CreatedAt,
                         LinkUpdatedAt = ft.UpdatedAt,
                         TagCreatedAt = ft.Tag.CreatedAt,
                         TagUpdatedAt = ft.Tag.UpdatedAt,
                         TagDeletedAt = ft.Tag.DeletedAt,
                     })
                     .GroupBy(ft => ft.OwnerId)
                     .Select(g => new
                     {
                         OwnerId = g.Key,
                         LinkCreated = g.Max(ft => ft.LinkCreatedAt),
                         LinkUpdated = g.Max(ft => ft.LinkUpdatedAt),
                         TagCreated = g.Max(ft => ft.TagCreatedAt),
                         TagUpdated = g.Max(ft => ft.TagUpdatedAt),
                         TagDeleted = g.Max(ft => ft.TagDeletedAt),
                     })
                     .ToListAsync(ct))
        {
            Track(row.OwnerId, row.LinkCreated);
            Track(row.OwnerId, row.LinkUpdated);
            Track(row.OwnerId, row.TagCreated);
            Track(row.OwnerId, row.TagUpdated);
            Track(row.OwnerId, row.TagDeleted);
        }

        // A transcode becoming ready, disappearing or being replaced changes the
        // resolvable job set; the parent Job carries completion and retry state.
        foreach (var row in await context.TranspilationJobs
                     .Where(tj => ownerIds.Contains(tj.UserId))
                     .Select(tj => new
                     {
                         OwnerId = tj.UserId,
                         tj.CreatedAt,
                         tj.UpdatedAt,
                         tj.DeletedAt,
                         JobUpdatedAt = tj.Job.UpdatedAt,
                         JobDeletedAt = tj.Job.DeletedAt,
                         JobCompletedAt = tj.Job.CompletedAt,
                     })
                     .GroupBy(tj => tj.OwnerId)
                     .Select(g => new
                     {
                         OwnerId = g.Key,
                         Created = g.Max(tj => tj.CreatedAt),
                         Updated = g.Max(tj => tj.UpdatedAt),
                         Deleted = g.Max(tj => tj.DeletedAt),
                         JobUpdated = g.Max(tj => tj.JobUpdatedAt),
                         JobDeleted = g.Max(tj => tj.JobDeletedAt),
                         JobCompleted = g.Max(tj => tj.JobCompletedAt),
                     })
                     .ToListAsync(ct))
        {
            Track(row.OwnerId, row.Created);
            Track(row.OwnerId, row.Updated);
            Track(row.OwnerId, row.Deleted);
            Track(row.OwnerId, row.JobUpdated);
            Track(row.OwnerId, row.JobDeleted);
            Track(row.OwnerId, row.JobCompleted);
        }

        // The minimum-track gate is owner behavior, not library content.
        foreach (var row in await context.UserSettings
                     .Where(s => ownerIds.Contains(s.UserId))
                     .Select(s => new
                     {
                         OwnerId = s.UserId,
                         s.CreatedAt,
                         s.UpdatedAt,
                         s.DeletedAt,
                     })
                     .GroupBy(s => s.OwnerId)
                     .Select(g => new
                     {
                         OwnerId = g.Key,
                         Created = g.Max(s => s.CreatedAt),
                         Updated = g.Max(s => s.UpdatedAt),
                         Deleted = g.Max(s => s.DeletedAt),
                     })
                     .ToListAsync(ct))
        {
            Track(row.OwnerId, row.Created);
            Track(row.OwnerId, row.Updated);
            Track(row.OwnerId, row.Deleted);
        }

        var needing = new List<Guid>(ownerIds.Count);

        foreach (var ownerId in ownerIds)
        {
            if (!markers.TryGetValue(ownerId, out var marker)
                || marker.HasUnsynced
                || marker.Oldest is not { } lastSync)
            {
                needing.Add(ownerId);
                continue;
            }

            if (latestChange.TryGetValue(ownerId, out var changedAt)
                && changedAt >= lastSync)
            {
                needing.Add(ownerId);
            }
        }

        return needing;
    }

    public async Task<IReadOnlyList<Playlist>> GetOwnerAutoPlaylistsAsync(
        Guid ownerId, CancellationToken ct = default)
    {
        return await _playlists
            .Where(p => p.OwnerId == ownerId && p.DeletedAt == null && p.IsAutoGenerated)
            .ToListAsync(ct);
    }

    // IRepository<Playlist> base members

    public async Task<IEnumerable<Playlist>> GetAllAsync(CancellationToken ct = default)
        => await _playlists.Where(p => p.DeletedAt == null).ToListAsync(ct);

    public async Task<IEnumerable<Playlist>> FindAsync(
        Expression<Func<Playlist, bool>> predicate, CancellationToken ct = default)
        => await _playlists.Where(p => p.DeletedAt == null).Where(predicate).ToListAsync(ct);

    public async Task<Playlist?> FirstOrDefaultAsync(
        Expression<Func<Playlist, bool>> predicate, CancellationToken ct = default)
        => await _playlists.Where(p => p.DeletedAt == null).FirstOrDefaultAsync(predicate, ct);

    public async Task<Playlist> AddAsync(Playlist entity, CancellationToken ct = default)
    {
        entity.CreatedAt = DateTime.UtcNow;
        var result = await _playlists.AddAsync(entity, ct);
        await context.SaveChangesAsync(ct);
        return result.Entity;
    }

    public async Task<IEnumerable<Playlist>> AddRangeAsync(
        IEnumerable<Playlist> entities, CancellationToken ct = default)
    {
        var list = entities.ToList();
        var now = DateTime.UtcNow;
        foreach (var e in list) e.CreatedAt = now;
        await _playlists.AddRangeAsync(list, ct);
        await context.SaveChangesAsync(ct);
        return list;
    }

    public void Update(Playlist entity)
    {
        entity.UpdatedAt = DateTime.UtcNow;
        _playlists.Update(entity);
    }

    public void Remove(Playlist entity)
    {
        entity.DeletedAt = DateTime.UtcNow;
        entity.UpdatedAt = DateTime.UtcNow;
        _playlists.Update(entity);
    }

    public void RemoveRange(IEnumerable<Playlist> entities)
    {
        var now = DateTime.UtcNow;
        var playlists = entities as Playlist[] ?? entities.ToArray();
        foreach (var e in playlists)
        {
            e.DeletedAt = now;
            e.UpdatedAt = now;
        }

        _playlists.UpdateRange(playlists);
    }

    public async Task<int> CountAsync(
        Expression<Func<Playlist, bool>>? predicate = null, CancellationToken ct = default)
    {
        var query = _playlists.Where(p => p.DeletedAt == null);
        if (predicate != null) query = query.Where(predicate);
        return await query.CountAsync(ct);
    }

    public async Task<bool> ExistsAsync(
        Expression<Func<Playlist, bool>> predicate, CancellationToken ct = default)
        => await _playlists.Where(p => p.DeletedAt == null).AnyAsync(predicate, ct);
