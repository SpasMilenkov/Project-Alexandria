-- Adding an album can add hundreds of items, so items are summarised as one row per playlist and
-- transaction instead of one row per item. EF sends each inserted row as its own statement, so a
-- later statement in the same transaction folds its counts into the row the first one wrote.
-- Removal is a tombstone (DeletedAt), and adding a removed track again revives it.
CREATE OR REPLACE FUNCTION audit_playlist_items_write(p_counts JSONB)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_row RECORD;
BEGIN
    FOR v_row IN
        SELECT p."Id", p."OwnerId", p."Name",
               (c.value ->> 'added')::INT   AS added,
               (c.value ->> 'removed')::INT AS removed
        FROM jsonb_each(p_counts) c
        JOIN "Playlists" p ON p."Id" = c.key::UUID
        WHERE NOT p."IsAutoGenerated"
          AND ((c.value ->> 'added')::INT > 0 OR (c.value ->> 'removed')::INT > 0)
    LOOP
        UPDATE "AuditLogs"
        SET "MetadataJson" = jsonb_build_object(
                'added',   COALESCE(("MetadataJson" ->> 'added')::INT, 0) + v_row.added,
                'removed', COALESCE(("MetadataJson" ->> 'removed')::INT, 0) + v_row.removed)
        WHERE "EntityType" = 'Playlist'
          AND "EntityId" = v_row."Id"
          AND "EventCode" = 'PlaylistItemsChanged'
          AND "Timestamp" >= now()
          AND "CorrelationId" IS NOT DISTINCT FROM audit_setting_uuid('app.correlation_id');

        IF NOT FOUND THEN
            PERFORM audit_write('Playlist', v_row."Id", 'PlaylistItemsChanged', 'Update',
                jsonb_build_object('added', v_row.added, 'removed', v_row.removed),
                v_row."OwnerId", NULL, v_row."Name");
        END IF;
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION audit_playlist_items_inserted()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    BEGIN
        PERFORM audit_playlist_items_write((
            SELECT COALESCE(jsonb_object_agg(playlist_id::TEXT, jsonb_build_object('added', added, 'removed', 0)), '{}'::JSONB)
            FROM (
                SELECT "PlaylistId" AS playlist_id, count(*) AS added
                FROM new_items
                WHERE "DeletedAt" IS NULL
                GROUP BY "PlaylistId"
            ) counts));
    EXCEPTION WHEN OTHERS THEN
        RAISE WARNING 'Audit logging failed for % %: %', TG_TABLE_NAME, TG_OP, SQLERRM;
    END;

    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION audit_playlist_items_updated()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    BEGIN
        PERFORM audit_playlist_items_write((
            SELECT COALESCE(jsonb_object_agg(playlist_id::TEXT, jsonb_build_object('added', added, 'removed', removed)), '{}'::JSONB)
            FROM (
                SELECT n."PlaylistId" AS playlist_id,
                       count(*) FILTER (WHERE o."DeletedAt" IS NOT NULL AND n."DeletedAt" IS NULL) AS added,
                       count(*) FILTER (WHERE o."DeletedAt" IS NULL AND n."DeletedAt" IS NOT NULL) AS removed
                FROM new_items n
                JOIN old_items o ON o."Id" = n."Id"
                GROUP BY n."PlaylistId"
            ) counts));
    EXCEPTION WHEN OTHERS THEN
        RAISE WARNING 'Audit logging failed for % %: %', TG_TABLE_NAME, TG_OP, SQLERRM;
    END;

    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION audit_playlist_items_deleted()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    BEGIN
        PERFORM audit_playlist_items_write((
            SELECT COALESCE(jsonb_object_agg(playlist_id::TEXT, jsonb_build_object('added', 0, 'removed', removed)), '{}'::JSONB)
            FROM (
                SELECT "PlaylistId" AS playlist_id, count(*) AS removed
                FROM old_items
                WHERE "DeletedAt" IS NULL
                GROUP BY "PlaylistId"
            ) counts));
    EXCEPTION WHEN OTHERS THEN
        RAISE WARNING 'Audit logging failed for % %: %', TG_TABLE_NAME, TG_OP, SQLERRM;
    END;

    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS playlist_items_insert_audit_trigger ON "PlaylistItems";
DROP TRIGGER IF EXISTS playlist_items_update_audit_trigger ON "PlaylistItems";
DROP TRIGGER IF EXISTS playlist_items_delete_audit_trigger ON "PlaylistItems";

-- Postgres allows transition tables only on single-event triggers without column lists.
CREATE TRIGGER playlist_items_insert_audit_trigger
    AFTER INSERT ON "PlaylistItems"
    REFERENCING NEW TABLE AS new_items
    FOR EACH STATEMENT
    EXECUTE FUNCTION audit_playlist_items_inserted();

CREATE TRIGGER playlist_items_update_audit_trigger
    AFTER UPDATE ON "PlaylistItems"
    REFERENCING OLD TABLE AS old_items NEW TABLE AS new_items
    FOR EACH STATEMENT
    EXECUTE FUNCTION audit_playlist_items_updated();

CREATE TRIGGER playlist_items_delete_audit_trigger
    AFTER DELETE ON "PlaylistItems"
    REFERENCING OLD TABLE AS old_items
    FOR EACH STATEMENT
    EXECUTE FUNCTION audit_playlist_items_deleted();
