using Alexandria.Data.Models;
using Alexandria.Data.Models.Enumerators;
using Alexandria.Tests.Common.Builders;
using Alexandria.Tests.Common.Fixtures;
using AwesomeAssertions;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace Alexandria.Tests.Integration.Audit;

public class PlaylistsAuditTriggerTests(DatabaseFixture fixture) : AuditTriggerTestBase(fixture)
{
    [Fact]
    public async Task UserPlaylist_lifecycleAndItemSummaries()
    {
        var tracks = new List<Guid>();

        await AsUserAsync(async db =>
        {
            for (var i = 0; i < 3; i++)
            {
                var seed = await StreamingSeedHelper.SeedStreamableFileAsync(db, UserId, $"track-{i}.mp3",
                    DateTime.UtcNow, 180, ct: Ct);
                tracks.Add(seed.JobId);
            }
        });

        Guid playlistId = Guid.Empty;
        List<Guid> itemIds = [];

        await AsUserAsync(async db =>
            (playlistId, itemIds) = await StreamingSeedHelper.SeedPlaylistAsync(db, UserId, "Road trip", tracks, Ct));

        await AsUserAsync(async db =>
            (await db.Playlists.SingleAsync(p => p.Id == playlistId, Ct)).Name = "Summer road trip");

        // Removing a track tombstones its item rather than deleting it.
        await AsUserAsync(async db => await db.PlaylistItems.Where(i => i.Id == itemIds[0])
            .ExecuteUpdateAsync(s => s.SetProperty(i => i.DeletedAt, DateTime.UtcNow), Ct));

        // A reorder changes positions only and is not an item change.
        await AsUserAsync(async db => await db.PlaylistItems.Where(i => i.Id == itemIds[1])
            .ExecuteUpdateAsync(s => s.SetProperty(i => i.Position, 9), Ct));

        await AsUserAsync(async db =>
            (await db.Playlists.SingleAsync(p => p.Id == playlistId, Ct)).DeletedAt = DateTime.UtcNow);

        (await SingleLogAsync(AuditEventCode.PlaylistCreated)).EntityName.Should().Be("Road trip");
        Metadata(await SingleLogAsync(AuditEventCode.PlaylistRenamed)).GetProperty("new").GetString()
            .Should().Be("Summer road trip");
        (await SingleLogAsync(AuditEventCode.PlaylistSoftDeleted)).OwnerId.Should().Be(UserId);

        var itemRows = await LogsAsync(AuditEventCode.PlaylistItemsChanged);
        itemRows.Should().HaveCount(2);
        Metadata(itemRows[0]).GetProperty("added").GetInt32().Should().Be(3);
        Metadata(itemRows[1]).GetProperty("removed").GetInt32().Should().Be(1);
    }

    [Fact]
    public async Task AutoGeneratedPlaylist_isNotAudited()
    {
        await AsActorAsync(null, db =>
        {
            db.Playlists.Add(new Playlist
            {
                Id = Guid.NewGuid(),
                Name = "Rock",
                OwnerId = UserId,
                IsAutoGenerated = true,
                CreatedAt = DateTime.UtcNow,
            });
            return Task.CompletedTask;
        });

        (await LogsAsync(AuditEventCode.PlaylistCreated)).Should().BeEmpty();
    }
}
