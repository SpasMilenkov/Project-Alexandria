using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Alexandria.Common.Helpers;
using Alexandria.Common.Mime;
using Alexandria.Common.Policies;
using Alexandria.Data.Models.Enumerators;
using Alexandria.Services.Preview;
using Alexandria.Services.Storage.Content.Mime;
using AwesomeAssertions;

namespace Alexandria.Tests.Unit.Mime;

/// <summary>
/// The frontend reads its MIME rules from a JSON catalog generated from the backend tables. These
/// tests keep that file in sync and guard the properties the frontend relies on.
/// </summary>
public class MimeCatalogTests
{
    private const string UpdateVariable = "ALEXANDRIA_UPDATE_MIME_CATALOG";

    private static readonly string[] CatalogPathSegments = ["Frontend", "src", "generated", "mime-catalog.json"];

    private static readonly JsonSerializerOptions WriteOptions = new()
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
    };

    [Fact]
    public void Catalog_committedFrontendFile_matchesBackendTables()
    {
        var path = CatalogPath();
        if (path is null)
            Assert.Skip("The Frontend sources are not checked out next to the Backend.");

        var expected = BuildCatalog();

        if (Environment.GetEnvironmentVariable(UpdateVariable) == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, expected.ToJsonString(WriteOptions) + "\n");
            return;
        }

        var regenerate = $"regenerate it with {UpdateVariable}=1 dotnet test Backend/Alexandria.Tests.Unit " +
                         $"--filter \"FullyQualifiedName~{nameof(MimeCatalogTests)}\"";

        File.Exists(path).Should().BeTrue($"{path} is missing; {regenerate}");

        var actual = JsonNode.Parse(File.ReadAllText(path));
        JsonNode.DeepEquals(expected, actual).Should().BeTrue($"{path} is out of date; {regenerate}");
    }

    [Fact]
    public void Categories_ruleTypes_areCanonical()
    {
        foreach (var (category, matcher) in MimeCategories.AllRules)
        {
            foreach (var type in matcher.Types)
                MimeAliases.Canonicalize(type).Should().Be(type, $"{category} lists {type}");

            matcher.Prefixes.Should().AllSatisfy(prefix => prefix.Should().EndWith("/"));
        }
    }

    [Fact]
    public void Categories_rules_areDisjoint()
    {
        foreach (var (category, matcher) in MimeCategories.AllRules)
        foreach (var type in matcher.Types)
        {
            var owners = MimeCategories.AllRules.Where(r => r.Matcher.Matches(type)).Select(r => r.Category);
            owners.Should().Equal([category], $"{type} must belong to exactly one category");
        }
    }

    [Fact]
    public void PreviewWorker_everyListedType_categorizesToAWorkerCategory()
    {
        foreach (var type in MimeCategories.PreviewWorker.Types)
            MimeCategories.UsesPreviewWorker(MimeCategories.Categorize(type)).Should().BeTrue(type);

        foreach (var prefix in MimeCategories.PreviewWorker.Prefixes)
            MimeCategories.UsesPreviewWorker(MimeCategories.Categorize($"{prefix}x-sample")).Should().BeTrue(prefix);
    }

    [Fact]
    public void PreviewWorker_categories_matchPreviewServiceRouting()
    {
        foreach (var category in Enum.GetValues<FileCategory>())
        {
            var routed = PreviewService.WorkerRoutingKey(category, "type/subtype") is not null;
            routed.Should().Be(MimeCategories.UsesPreviewWorker(category), category.ToString());
        }
    }

    [Fact]
    public void Groups_everyTypeTheResolverCanEmit_belongsToExactlyOneGroup()
    {
        var emitted = ExtensionMimeMap.AllTypes
            .Concat(MimeFileNameMap.AllTypes)
            .Concat(IsoBmffBrands.AllTypes)
            .Distinct(StringComparer.Ordinal);

        foreach (var type in emitted)
        {
            var owners = FileGroups.All.Where(g => g.Matcher.Matches(type)).Select(g => g.Name).ToList();
            owners.Should().ContainSingle($"{type} is stored for uploads, so a policy group must own it");
        }
    }

    private static JsonObject BuildCatalog()
    {
        var aliases = new JsonObject();
        foreach (var (alias, canonical) in MimeAliases.Table.OrderBy(pair => pair.Key, StringComparer.Ordinal))
            aliases[alias] = canonical;

        var groups = new JsonObject();
        foreach (var (name, matcher) in FileGroups.All)
            groups[name] = ToJson(matcher);

        return new JsonObject
        {
            ["$comment"] = $"Generated by {nameof(MimeCatalogTests)} in Alexandria.Tests.Unit from the backend " +
                           $"MIME tables. Do not edit by hand; run with {UpdateVariable}=1 to regenerate.",
            ["aliases"] = aliases,
            ["previewWorker"] = ToJson(MimeCategories.PreviewWorker),
            ["autoTag"] = ToJson(AutoTagSupportedFileTypes.Supported),
            ["groups"] = groups
        };
    }

    private static JsonObject ToJson(MimeMatcher matcher) => new()
    {
        ["prefixes"] = new JsonArray([.. matcher.Prefixes.Select(p => JsonValue.Create(p))]),
        ["types"] = new JsonArray([.. matcher.Types.Select(t => JsonValue.Create(t))])
    };

    private static string? CatalogPath()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            var hasBackend = Directory.Exists(Path.Combine(dir.FullName, "Backend"));
            var hasFrontend = File.Exists(Path.Combine(dir.FullName, "Frontend", "package.json"));

            if (hasBackend && hasFrontend)
                return Path.Combine([dir.FullName, .. CatalogPathSegments]);
        }

        return null;
    }
}
