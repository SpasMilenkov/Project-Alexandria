using Alexandria.Data.Context;
using Alexandria.Repositories;
using AwesomeAssertions;
using Microsoft.EntityFrameworkCore;

namespace Alexandria.Tests.Unit.Repositories;

public class ProfileStatsQueryTests
{
    private static readonly DateTime Now = new(2026, 11, 12, 12, 0, 0, DateTimeKind.Utc);

    private static string Sql()
    {
        var options = new DbContextOptionsBuilder<AlexandriaDbContext>()
            .UseNpgsql("Host=localhost;Database=translation_only;Username=postgres;Password=postgres")
            .Options;
        using var context = new AlexandriaDbContext(options);

        return UserRepository.BuildProfileStatsQuery(context, Guid.NewGuid(), Now).ToQueryString();
    }

    [Fact]
    public void Every_total_is_read_in_the_same_query()
    {
        var sql = Sql();

        sql.Should().Contain("\"Files\"");
        sql.Should().Contain("\"Directories\"");
        sql.Should().Contain("\"Playlists\"");
        sql.Should().Contain("\"Tags\"");
        sql.Should().Contain("\"SignedUrls\"");
        sql.Should().Contain("\"StreamHistory\"");
    }

    [Fact]
    public void Trashed_items_are_left_out()
    {
        Sql().Should().Contain("\"DeletedAt\" IS NULL");
    }

    [Fact]
    public void Listening_totals_read_zero_without_any_history()
    {
        Sql().Should().Contain("COALESCE(sum(");
    }

    [Fact]
    public void Only_links_that_still_open_count_as_active()
    {
        var sql = Sql();

        sql.Should().Contain("s.\"ExpiresAt\" > @now");
        sql.Should().Contain("s.\"AccessCount\" < s.\"MaxAccessCount\"");
    }

    [Fact]
    public void Auto_playlists_are_not_counted_as_the_users_own()
    {
        Sql().Should().Contain("NOT (p.\"IsAutoGenerated\")");
    }
}
