using Alexandria.Data.Models;
using Alexandria.Data.Models.Enumerators;
using Alexandria.Dto.Files;
using Alexandria.Dto.Files.Streaming.Playlist;

namespace Alexandria.Common.Repositories;

/// <summary>Repository for <see cref="Playlist"/> persistence operations.</summary>
public interface IPlaylistRepository : IRepository<Playlist>
{
    /// <summary>Creates and persists a new playlist, cascading timestamps to any initial items.</summary>
    Task<Playlist> CreateAsync(Playlist entity, CancellationToken ct = default);

    /// <summary>Persists changes to an existing playlist and returns the updated instance.</summary>
    Task<Playlist> UpdateAsync(Playlist entity, CancellationToken ct = default);

    /// <summary>Sets the starred flag when the given user owns the live playlist; returns false when absent.</summary>
    Task<bool> SetPlaylistFavoriteAsync(Guid playlistId, Guid userId, bool isStarred, CancellationToken ct = default);

    /// <summary>Returns a summary projection with a live item count. Used after mutations.</summary>
    Task<PlaylistDto?> GetSummaryAsync(Guid id, Guid userId, CancellationToken ct = default);

    /// <summary>
    /// Returns the playlist with its ordered non-deleted items projected to a detail DTO,
    /// including the representation list for each item resolved via the
    /// PlaylistItem -> TranspilationJob -> FileVersion -> File chain.
    /// </summary>
    Task<PlaylistDetailDto?> GetWithItemsAsync(Guid id, Guid userId, CancellationToken ct = default);

    /// <summary>Returns a paginated list of playlists owned by the given user.
    /// Optional origin/kind/starred narrow the set before counting; a search term
    /// matches the name and description, optionally widening to item file names and
    /// track titles; sort and direction order before paging.</summary>
    Task<PaginatedResult<PlaylistDto>> GetByUserAsync(
        Guid userId,
        int page,
        int pageSize,
        bool? isAutoGenerated = null,
        AutoGroupKind? kind = null,
        bool isStarred = false,
        PlaylistSort sort = PlaylistSort.Newest,
        SortDirection direction = SortDirection.Desc,
        string? query = null,
        bool searchItems = false,
        CancellationToken ct = default);

    /// <summary>Soft-deletes the playlist and cascades the deletion to all its items atomically.</summary>
    Task SoftDeleteAsync(Guid playlistId, Guid userId, CancellationToken ct = default);

    /// <summary>Updates each item's Position according to the provided ordered ID sequence.</summary>
    Task ReorderItemsAsync(Guid playlistId, Guid[] orderedItemIds, CancellationToken ct = default);

    /// <summary>
    /// Appends an item at the next available position and returns the projected DTO,
    /// resolving file name, MIME type, segment prefix and representations from
    /// the TranspilationJob chain.
    /// </summary>
    Task<PlaylistItemDto> AddItemAsync(PlaylistItem item, CancellationToken ct = default);

    /// <summary>Soft-deletes a single playlist item.</summary>
    Task RemoveItemAsync(Guid playlistId, Guid itemId, Guid userId, CancellationToken ct = default);

    /// <summary>Returns whether the given user is the owner of the playlist and it has not been deleted.</summary>
    Task<bool> IsOwnerAsync(Guid playlistId, Guid userId, CancellationToken ct = default);

    /// <summary>
    /// Finds a live auto-maintained playlist by its grouping key. Only the key columns
    /// of the given kind are matched; pass null for the rest.
    /// </summary>
    Task<Playlist?> GetAutoPlaylistAsync(
        Guid ownerId,
        AutoGroupKind kind,
        string? artistKey,
        string? albumKey,
        Guid? tagId,
        string? genreKey,
        int? decade,
        CancellationToken ct = default);

    /// <summary>
    /// Every item of every given playlist including soft-deleted rows, keyed by
    /// playlist id and ordered by item id inside each playlist. Missing keys mean
    /// the playlist has no item rows.
    /// </summary>
    Task<IReadOnlyDictionary<Guid, IReadOnlyList<PlaylistItemState>>> GetItemsIncludingDeletedForPlaylistsAsync(
        Guid[] playlistIds, CancellationToken ct = default);

    /// <summary>
    /// Acquires the session-level advisory lock that serializes auto-playlist
    /// syncs for one owner across processes. The lock lives on a dedicated open
    /// connection; dispose the returned handle to release the lock and close the
    /// connection.
    /// </summary>
    Task<IAsyncDisposable> AcquireOwnerSyncLockAsync(
        Guid ownerId, CancellationToken ct = default);

    /// <summary>
    /// Ids of the owner's live auto playlists that hold a live item bound to any
    /// transcode job of any of the given files. One query for a coalesced batch.
    /// </summary>
    Task<IReadOnlyList<Guid>> GetOwnerAutoPlaylistIdsForFilesAsync(
        Guid ownerId, Guid[] fileIds, CancellationToken ct = default);

    /// <summary>
    /// Applies one owner batch of reconciler diffs: appends new items after the
    /// live maximum position, revives system tombstones, soft-deletes removed live
    /// rows, and stamps every playlist's LastSyncedAt. One save for the batch.
    /// </summary>
    Task ApplyAutoDiffsAsync(
        Guid ownerId, IReadOnlyList<AutoPlaylistDiff> diffs, CancellationToken ct = default);

    /// <summary>
    /// Ids of live auto Tag-kind playlists whose tag is a genre-facet child. Parent
    /// rollups replace these (D17); the worker dissolves them so they do not linger
    /// under the creation-hysteresis rule.
    /// </summary>
    Task<IReadOnlyList<Guid>> GetSupersededGenrePlaylistIdsAsync(
        Guid ownerId, CancellationToken ct = default);

    /// <summary>Distinct owners of live files. Sweep entry: covers owners whose files
    /// predate every playlist event, so existing libraries get playlists too.</summary>
    Task<IReadOnlyList<Guid>> GetSyncOwnerIdsAsync(CancellationToken ct = default);

    /// <summary>Live auto-maintained playlists of one owner, with grouping columns.</summary>
    Task<IReadOnlyList<Playlist>> GetOwnerAutoPlaylistsAsync(Guid ownerId, CancellationToken ct = default);
}